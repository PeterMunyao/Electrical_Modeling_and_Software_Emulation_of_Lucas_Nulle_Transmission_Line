# Calculate Net Load (PV - Load)
df['Net_Load'] = df['PV_System_MW'] - df['General_Load_MW']

# ============================================
# SINGLE PLOT: All four variables
# ============================================
fig, ax = plt.subplots(figsize=(8, 6))

# Plot all four data series
ax.plot(df['Time'], df['General_Load_MW'], 'r-', linewidth=2.5, label='General Load', alpha=0.9)
ax.plot(df['Time'], df['PV_System_MW'], 'orange', linewidth=2.5, label='PV System', alpha=0.9)
