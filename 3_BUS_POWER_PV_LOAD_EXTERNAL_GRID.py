ax.plot(df['Time'], df['Net_Load'], 'g-', linewidth=2.0, label='Net Load (PV - Load)', alpha=0.8)

# Fill areas for excess and deficit
ax.fill_between(df['Time'], 0, df['Net_Load'], where=(df['Net_Load'] > 0), 
                  color='green', alpha=0.2, label='Excess Generation')
ax.fill_between(df['Time'], 0, df['Net_Load'], where=(df['Net_Load'] < 0), 
                  color='red', alpha=0.2, label='Deficit')

# Add zero reference line
ax.axhline(y=0, color='black', linestyle='-', linewidth=1.5, alpha=0.5)

# Labels
