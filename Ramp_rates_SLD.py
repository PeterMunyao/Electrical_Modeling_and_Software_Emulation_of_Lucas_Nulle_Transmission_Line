# Generate timestamps (6:15 to 20:25, 5-minute intervals)
start_time = datetime(2024, 5, 19, 6, 15, 0)
timestamps = [start_time + pd.Timedelta(minutes=5*i) for i in range(len(grid_data))]

# Create DataFrame
df = pd.DataFrame({
    'Time': timestamps,
    'External_Grid_MW': grid_data,
    'General_Load_MW': load_data,
    'PV_System_MW': pv_data
})

# Calculate ramp rates (MW per 5-minute interval)
df['PV_Ramp'] = df['PV_System_MW'].diff()
df['Grid_Ramp'] = df['External_Grid_MW'].diff()
df['Load_Ramp'] = df['General_Load_MW'].diff()

# Create single combined plot with all ramp rates
fig, ax = plt.subplots(figsize=(7, 5))

# Plot all three ramp rates
ax.plot(df['Time'], df['PV_Ramp'], 'orange', linewidth=2.0, label='PV Ramp Rate')
ax.plot(df['Time'], df['Grid_Ramp'], 'b-', linewidth=2.0, label='External Grid Ramp Rate')
ax.plot(df['Time'], df['Load_Ramp'], 'r-', linewidth=2.0, label='Load Ramp Rate')

# Add zero reference line
ax.axhline(y=0, color='black', linestyle='-', linewidth=1.5, alpha=0.5)

# Labels
ax.set_ylabel('Ramp Rate (MW/5min)', fontweight='bold')
ax.set_xlabel('19/May/2024 (UTC) Serres C, Greece', fontweight='bold')

# Set Y-axis limits to -5 and 5
ax.set_ylim(-5, 5)
ax.set_yticks(np.arange(-5, 5.1, 1))

# Set grid lines to dotted
ax.grid(True, linestyle=':', alpha=0.5, linewidth=1.5)

# Legend below the plot
ax.legend(loc='lower center', bbox_to_anchor=(0.5, -0.35), ncol=2, fontsize=14)

# Format x-axis - NO ROTATION
ax.xaxis.set_major_formatter(mdates.DateFormatter('%H:%M'))
ax.xaxis.set_major_locator(mdates.HourLocator(interval=2))
ax.tick_params(axis='x', rotation=0)
ax.tick_params(axis='both', which='major', labelsize=17, width=2)

# Adjust layout
plt.tight_layout()
plt.subplots_adjust(bottom=0.15)

# Save as PDF
plt.savefig('Ramp_Rates_Combined_May19_2024.pdf', format='pdf', bbox_inches='tight', dpi=300)

# Display the plot
